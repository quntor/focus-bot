export type PrivacyPolicyConfig = {
  operatorName: string
  contactEmail: string
}

const escapeHtml = (value: string) =>
  value.replace(/[&<>"']/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]!)

export function renderPrivacyPolicy(config: PrivacyPolicyConfig): string {
  const operator = escapeHtml(config.operatorName)
  const contact = escapeHtml(config.contactEmail)
  return `<!doctype html>
<html lang="ru">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Политика обработки персональных данных — Фокус</title>
  <style>body{max-width:760px;margin:40px auto;padding:0 20px;font:16px/1.55 system-ui,sans-serif;color:#17202a}h1,h2{line-height:1.2}small{color:#5d6d7e}</style>
</head>
<body>
  <h1>Политика обработки персональных данных</h1>
  <p><small>Редакция от 26 сентября 2026 года</small></p>
  <p>Оператор: <strong>${operator}</strong>. Контакт по вопросам персональных данных: <strong>${contact}</strong>.</p>

  <h2>1. Что это за сервис</h2>
  <p>«Фокус» — тестовый Telegram-бот для планирования задач и фокус-сессий. Политика относится к данным, которые пользователь передаёт боту и которые возникают при работе с ним.</p>

  <h2>2. Какие данные обрабатываются</h2>
  <ul>
    <li>Telegram ID и источник запуска бота;</li>
    <li>часовой пояс, настройки, задачи, намерения, отчёты, профиль и ритуал работы;</li>
    <li>сведения о фокус-сессиях, действиях в боте, начисленных баллах и серии;</li>
    <li>голосовое сообщение — только для получения расшифровки; аудио не сохраняется в базе или на диске приложения;</li>
    <li>технические события и обезличенные идентификаторы, необходимые для надёжности, аналитики и отчётности программы Сбер 500.</li>
  </ul>

  <h2>3. Цели и основание обработки</h2>
  <p>Данные используются для работы бота, персонализации фокус-сессий, восстановления состояния после перезапуска, продуктовой аналитики, предотвращения злоупотреблений и подготовки обезличенной конкурсной отчётности. Основание обработки — согласие пользователя, выраженное кнопкой «Согласен» до начала работы.</p>

  <h2>4. Как обрабатываются данные</h2>
  <p>Сообщения доставляются через Telegram. Тексты задач, намерений и отчётов могут передаваться подключённому провайдеру генеративной модели; голосовые сообщения — провайдеру распознавания речи. Провайдеры получают только данные, необходимые для конкретного запроса. Решения о баллах, серии и изменении состояния принимает код приложения, а не модель.</p>
  <p>Рабочие данные хранятся в базе приложения. Доступ к ним ограничен участниками команды, которым он нужен для разработки и поддержки. Сырые тексты и аудио не включаются в аналитические выгрузки.</p>

  <h2>5. Срок хранения и удаление</h2>
  <p>Данные хранятся до отзыва согласия, прекращения теста или достижения указанных целей. Пользователь может удалить учётную запись и связанные с ней рабочие данные командой <code>/delete_me</code>. После удаления могут сохраниться технические журналы без Telegram ID и без возможности связать их с удалённым пользователем средствами приложения.</p>

  <h2>6. Права пользователя</h2>
  <p>Пользователь может запросить сведения об обработке, уточнение, блокирование или удаление данных, а также отозвать согласие по адресу ${contact}. Отзыв согласия прекращает использование бота, поскольку без обработки данных сервис не работает.</p>

  <h2>7. Защита и изменения политики</h2>
  <p>Оператор применяет разграничение доступа, защищённое HTTPS-соединение, секрет вебхука, минимизацию журналов и резервное копирование. При существенном изменении целей или состава обработки пользователь получит новую редакцию политики до продолжения работы.</p>
</body>
</html>`
}
